#!/usr/bin/env python3
"""Contact sheet + text catalogue of work/_lib/objects.py.

    python3 docs/redesign/make_objects_sheet.py
    -> docs/redesign/objects.png  (every object at 128 px, its function name under it)
    -> docs/redesign/OBJECTS.md   (the same as text, for models that cannot see images)
"""
import inspect
import io
import sys
from pathlib import Path

import cairosvg
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "work/_lib"))
import objects as O  # noqa: E402

# the size each object gets on the sheet so that it fits 8..120 standing on y = 118
SHEET_SIZE = {"speech_bubble": 104, "envelope": 108, "paper_plane": 100, "cloud": 108, "browser_window": 108,
              "globe": 100, "shield": 88, "lock": 72, "key": 104, "card": 108, "coin": 96, "gear": 100,
              "folder": 108, "camera_lens": 100, "play_button": 108, "music_note": 92, "book": 80,
              "phone_handset": 100, "battery": 60, "calendar_page": 100, "goal_ring": 90, "energy_ball": 90,
              "wizard_hat": 108, "crystal": 72, "football": 100, "team_ball": 96, "die": 86, "board_tiles": 108}


def render(svg_text, px=128):
    png = cairosvg.svg2png(bytestring=svg_text.encode(), output_width=px, output_height=px)
    return Image.open(io.BytesIO(png)).convert("RGBA")


def main():
    cols, cell, lab = 7, 150, 34
    rows = (len(O.CATALOGUE) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * cell + 20, rows * (cell + lab) + 60), "#f6f5f4")
    dr = ImageDraw.Draw(sheet)
    try:
        font = ImageFont.truetype("DejaVuSans.ttf", 13)
        big = ImageFont.truetype("DejaVuSans.ttf", 18)
    except OSError:
        font = big = ImageFont.load_default()
    dr.text((14, 14), "work/_lib/objects.py - f(ic, cx, base, size, ramp=...)  (cx=64, base=118 here)", fill="#241f31", font=big)
    md = ["# Object catalogue (work/_lib/objects.py)", "",
          "Generated by `python3 docs/redesign/make_objects_sheet.py`; picture: `docs/redesign/objects.png`.",
          "Every function: `f(ic, cx, base, size, ramp=RAMP[\"<HIG ramp>\"], name=...)` -> the outline.",
          "`cx` = centre x, `base` = bottom edge incl. thickness (118 = the baseline), `size` = width.",
          "The box below is what `size` on the sheet gives (x0 y0 x1 y1 in the 128 canvas).", "",
          "| function | use | size on sheet | box | what it looks like |", "|---|---|---|---|---|"]
    for i, (fname, kw, use) in enumerate(O.CATALOGUE):
        ic = O.gk.Icon(fname)
        g = getattr(O, fname)(ic, 64, 118, SHEET_SIZE[fname], **kw)
        tmp = ROOT / f"docs/redesign/.{fname}.svg"
        ic.save(tmp)
        im = render(tmp.read_text())
        tmp.unlink()
        x, y = 10 + (i % cols) * cell, 50 + (i // cols) * (cell + lab)
        sheet.paste(im, (x + 11, y + 6), im)
        dr.text((x + 6, y + cell - 4), fname, fill="#241f31", font=font)
        x0, y0, x1, y1 = (round(v) for v in g.bounds)
        doc = (inspect.getdoc(getattr(O, fname)) or "").split("\n")[0]
        md.append(f"| `{fname}` | {use} | {SHEET_SIZE[fname]} | {x0} {y0} {x1} {y1} | {doc} |")
    sheet.save(ROOT / "docs/redesign/objects.png")
    md += ["", "Ramps: " + ", ".join(f"`{k}`" for k in O.RAMP), ""]
    (ROOT / "docs/redesign/OBJECTS.md").write_text("\n".join(md) + "\n")
    print("wrote docs/redesign/objects.png + docs/redesign/OBJECTS.md")


if __name__ == "__main__":
    main()
