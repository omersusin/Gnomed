#!/usr/bin/env python3
"""Generate the per-style files of the Gnomed icon pack from pack/styles.json.

Faithful is the base: app/src/main/res/xml/appfilter.xml (edited by candybar_add.py).
For every other style S this writes
  app/src/S/res/xml/appfilter.xml and app/src/S/assets/appfilter.xml
    = the main appfilter with drawable="X" replaced by styles.json[icons][X][S]
      (apps without an S variant keep their Faithful drawable)
and for every style (incl. faithful)
  app/src/S/res/values/gnomed_style.xml   (string gnomed_style = S)

Only <item ...> drawable attributes are rewritten; nothing is removed.
--check exits 1 if the committed files differ from what would be generated (CI).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAIN_APPFILTER = ROOT / "app/src/main/res/xml/appfilter.xml"
DRAWABLE_XML = ROOT / "app/src/main/res/xml/drawable.xml"
NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")
ITEM_RE = re.compile(r'(<item\b[^>]*\bdrawable=")([^"]+)(")')


def build(cfg):
    styles = cfg["styles"]
    icons = cfg.get("icons", {})
    base = MAIN_APPFILTER.read_text(encoding="utf-8")
    gallery = set(re.findall(r'<item\b[^>]*\bdrawable="([^"]+)"', DRAWABLE_XML.read_text(encoding="utf-8")))
    errors = []
    for primary, per_style in icons.items():
        for s, name in per_style.items():
            if s not in styles:
                errors.append(f"{primary}: unknown style '{s}'")
            if not NAME_RE.match(name):
                errors.append(f"{primary}: invalid drawable name '{name}'")
            elif name not in gallery:
                errors.append(f"{primary}: '{name}' ({s}) is not in drawable.xml")
    if errors:
        raise SystemExit("styles.json errors:\n  " + "\n  ".join(errors))

    out = {}
    for s in styles:
        out[ROOT / f"app/src/{s}/res/values/gnomed_style.xml"] = (
            '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/gen_styles.py - do not edit -->\n'
            f'<resources>\n    <string name="gnomed_style" translatable="false">{s}</string>\n</resources>\n')
        if s == styles[0]:
            continue
        text = ITEM_RE.sub(lambda m: m.group(1) + icons.get(m.group(2), {}).get(s, m.group(2)) + m.group(3), base)
        text = text.replace("<resources>", f"<resources>\n    <!-- generated by tools/gen_styles.py for style '{s}' - edit app/src/main + pack/styles.json instead -->", 1)
        out[ROOT / f"app/src/{s}/res/xml/appfilter.xml"] = text
        out[ROOT / f"app/src/{s}/assets/appfilter.xml"] = text
    return out


def main():
    check = "--check" in sys.argv
    cfg = json.loads((ROOT / "pack/styles.json").read_text(encoding="utf-8"))
    stale = []
    for path, text in build(cfg).items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("out of date (run tools/gen_styles.py):", *stale, sep="\n  ")
        sys.exit(1)
    print(("would update" if check else "updated") + f": {len(stale)} file(s)")


if __name__ == "__main__":
    main()
