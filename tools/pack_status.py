#!/usr/bin/env python3
"""Run the quality gate on every app and write
  docs/APPS.md   - the state of every app (redesigned?, approval, slots, next step) - START HERE
  docs/STATUS.md - every gate FAIL/WARN, worst first

    python3 tools/pack_status.py          (takes a few minutes: it runs check_icon on every app)
"""
import json
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def gate(slug):
    out = subprocess.run([sys.executable, str(ROOT / "tools/check_icon.py"), slug, "--json"], capture_output=True, text=True, cwd=ROOT)
    try:
        return slug, json.loads(out.stdout)
    except json.JSONDecodeError:
        return slug, [{"scope": "app", "check": "gate", "status": "FAIL", "value": out.stderr[-200:], "fix": "run check_icon.py by hand"}]


def main():
    slugs = sorted(p.parent.name for p in (ROOT / "work").glob("*/source.png") if not p.parent.name.startswith("_"))
    with ThreadPoolExecutor(4) as ex:
        res = dict(ex.map(gate, slugs))
    rows = []
    for s, r in res.items():
        f = [x for x in r if x["status"] == "FAIL"]
        w = [x for x in r if x["status"] == "WARN"]
        rows.append((len(f), len(w), s, f, w))
    rows.sort(key=lambda t: (-t[0], -t[1], t[2]))
    lines = ["# Pack status", "",
             "Generated by `python3 tools/pack_status.py` (the quality gate `tools/check_icon.py` on every app).",
             "Worst first. `redesign` FAIL = the app is still the logo on a plate: redesign it with",
             "REDESIGN.md (`python3 tools/new_redesign.py <slug>`), then `tools/pack_refresh.py <slug>`.",
             "Other FAIL/WARN: the recipes in docs/PLAYBOOK.md#fix-fail (tools/next.py <slug> prints the one you need).", "",
             f"Apps: {len(rows)} · with FAIL: {sum(1 for r in rows if r[0])} · with WARN: {sum(1 for r in rows if r[1])}", "",
             "| App | FAIL | WARN | Issues (style · check · value → recipe) |", "|---|---|---|---|"]
    for nf, nw, s, f, w in rows:
        issues = "; ".join(f'{x["scope"]} · {x["check"]} · {str(x["value"])[:40]} → {x["fix"].split(":")[0] if x["fix"] else ""}' for x in f + w)
        lines.append(f"| `{s}` | {nf} | {nw} | {issues or 'clean'} |")
    (ROOT / "docs/STATUS.md").write_text("\n".join(lines) + "\n")
    print(f"docs/STATUS.md: {len(rows)} apps")
    write_apps(res)


NOTES = {   # owner decisions that a table cell cannot show
    "kafa_topu_2": "still has characters (two faces); the owner agreed to redo it with objects only "
                   "(ball + boot): \"Evet, yeni oturumda\" (2026-11-21)",
}


def write_apps(res):
    sys.path.insert(0, str(ROOT / "tools"))
    import next as nx
    icons = json.loads((ROOT / "pack/styles.json").read_text())["icons"]
    rows = []
    for slug, r in res.items():
        w = ROOT / "work" / slug
        text = nx.design_text(w)
        red = (w / "redesign.py").exists() and "copy the approved concept here" not in (w / "redesign.py").read_text()
        appr = nx.line(text, "approved") if red else ""
        aq = nx.QUOTED_DATED.search(appr or "")
        approved = (appr.split("[")[0].strip()[:70] if aq else ("-" if not red else "NOT a quote: " + appr[:40]))
        final = nx.line(text, "final")
        final = final.split("[")[0].strip()[:40] if nx.quoted(final) else "-"
        if red:
            st = nx.line(text, "styles") or "-"
            slots = st.split(" - ")[0][:60]
        else:
            slots = "automatic plate / disc / rim / symbol"
        in_pack = (ROOT / f"app/src/main/res/drawable-nodpi/{slug}.png").exists()
        ladder = nx.line(text, "ladder") or ("-" if red else "none (logo on a plate)")
        chars = nx.line(text, "characters") or ("-" if red else "")
        nf = sum(x["status"] == "FAIL" for x in r)
        nw = sum(x["status"] == "WARN" for x in r)
        last = subprocess.run(["git", "log", "-1", "--format=%ad", "--date=short", "--", f"work/{slug}"],
                              capture_output=True, text=True, cwd=ROOT).stdout.strip() or "-"
        state, _ = nx.state_of(slug, cheap=True, use_git=False)
        nxt = {"NOT_STARTED": "redesign (owner picks the app)", "DONE": "done", "REDO": "REDO (owner asked)",
               "BUILD": "BUILD (no Symbol / not built)", "ASK_Q2": "ASK_Q2 (owner's final answer missing)"}.get(state, state)
        rows.append(dict(slug=slug, red=red, approved=approved, final=final, slots=slots, ladder=ladder, chars=chars,
                         gate=f"{nf} / {nw}", last=last, next=nxt, pack="yes" if in_pack else "no",
                         slots_pack=", ".join(f"{k}={v}" for k, v in icons.get(slug, {}).items()) or "faithful only"))
    rows.sort(key=lambda d: (not d["red"], d["slug"]))
    nred = sum(d["red"] for d in rows)
    done = sum(d["next"] == "done" for d in rows)
    out = ["# Apps — the state of every app", "",
           "Generated by `python3 tools/pack_status.py` — do not edit by hand. For one app's next step run",
           "`python3 tools/next.py <slug>`; for which app to do next run `python3 tools/next.py`.", "",
           f"**{nred} of {len(rows)} apps redesigned** ({done} finished: approved, in the pack, logged). "
           f"The other {len(rows) - nred} are still the old automatic \"logo on a plate\" — the owner chooses which one is next.", "",
           "Columns: *approved* = the owner's Q1 answer (quote + date); *final* = his Q2 answer; *slots* = which design is",
           "in which style (design.md `styles:`); *ladder* = REDESIGN.md §3 level; *gate* = check_icon FAIL / WARN;",
           "*next* = the state `tools/next.py` reports.", ""]
    for slug, note in NOTES.items():
        out.append(f"- **`{slug}`**: {note}.")
    out += ["", "## Redesigned", "",
            "| App | approved (Q1) | final (Q2) | slots | ladder | characters | gate F/W | last commit | next |",
            "|---|---|---|---|---|---|---|---|---|"]
    for d in rows:
        if d["red"]:
            out.append(f"| `{d['slug']}` | {d['approved']} | {d['final']} | {d['slots']} | {d['ladder']} | {d['chars']} | "
                       f"{d['gate']} | {d['last']} | {d['next']} |")
    out += ["", "## Not redesigned yet (logo on a plate)", "",
            "| App | in pack | pack slots | gate F/W | last commit | next |", "|---|---|---|---|---|---|"]
    for d in rows:
        if not d["red"]:
            out.append(f"| `{d['slug']}` | {d['pack']} | {d['slots_pack']} | {d['gate']} | {d['last']} | {d['next']} |")
    (ROOT / "docs/APPS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"docs/APPS.md: {nred} of {len(rows)} redesigned")


if __name__ == "__main__":
    main()
