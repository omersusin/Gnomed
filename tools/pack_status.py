#!/usr/bin/env python3
"""Run the quality gate on every app and write docs/STATUS.md - the to-do list for
contributors (worst first).   python3 tools/pack_status.py"""
import json
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def gate(slug):
    out = subprocess.run([sys.executable, str(ROOT / "tools/check_icon.py"), slug, "--json"], capture_output=True, text=True, cwd=ROOT)
    try:
        return slug, json.loads(out.stdout)
    except json.JSONDecodeError:
        return slug, [{"scope": "app", "check": "gate", "status": "FAIL", "value": out.stderr[-200:], "fix": "run check_icon.py by hand"}]


def main():
    slugs = sorted(p.parent.name for p in (ROOT / "work").glob("*/source.png") if not p.parent.name.startswith("_"))
    with ThreadPoolExecutor(4) as ex:
        res = dict(ex.map(gate, slugs))
    rows = []
    for s, r in res.items():
        f = [x for x in r if x["status"] == "FAIL"]
        w = [x for x in r if x["status"] == "WARN"]
        rows.append((len(f), len(w), s, f, w))
    rows.sort(key=lambda t: (-t[0], -t[1], t[2]))
    lines = ["# Pack status", "",
             "Generated by `python3 tools/pack_status.py` (the quality gate `tools/check_icon.py` on every app).",
             "Worst first. `redesign` FAIL = the app is still the logo on a plate: redesign it with",
             "REDESIGN.md (`python3 tools/new_redesign.py <slug>`), then `tools/pack_refresh.py <slug>`.",
             "Other WARNs: recipes in docs/course/04-recipes.md.", "",
             f"Apps: {len(rows)} · with FAIL: {sum(1 for r in rows if r[0])} · with WARN: {sum(1 for r in rows if r[1])}", "",
             "| App | FAIL | WARN | Issues (style · check · value → recipe) |", "|---|---|---|---|"]
    for nf, nw, s, f, w in rows:
        issues = "; ".join(f'{x["scope"]} · {x["check"]} · {str(x["value"])[:40]} → {x["fix"].split(":")[0] if x["fix"] else ""}' for x in f + w)
        lines.append(f"| `{s}` | {nf} | {nw} | {issues or 'clean'} |")
    (ROOT / "docs/STATUS.md").write_text("\n".join(lines) + "\n")
    print(f"docs/STATUS.md: {len(rows)} apps")


if __name__ == "__main__":
    main()
